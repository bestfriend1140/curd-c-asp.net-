import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env');

const defaults = {
  API_BASE_URL: 'http://localhost:5044',
};

function parseEnv(contents) {
  const values = {};

  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const separator = line.indexOf('=');
    if (separator === -1) continue;

    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    values[key] = value;
  }

  return values;
}

let env = { ...defaults };
try {
  env = { ...env, ...parseEnv(readFileSync(envPath, 'utf8')) };
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

const apiBaseUrl = env.API_BASE_URL || defaults.API_BASE_URL;

const output = `// Generated by scripts/generate-env.mjs from .env. Do not edit by hand.
export const environment = {
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
};
`;

const outPath = resolve(root, 'src', 'environments', 'environment.ts');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, output, 'utf8');

console.log(`[env] API_BASE_URL=${apiBaseUrl}`);
